#!/usr/bin/env python3
"""Migrate one TS3 virtual server (SQLite) into a fresh TeamSpeak 6 database.

Imports channels, groups, permissions, server settings, tokens and IP bans.
Everything bound to a client UID (TS3 UIDs are SHA-1, TS6 UIDs are SHA-256 of the
same public key, so they cannot be converted offline) is written to a side
database for the reconnect remapper instead.

Never touches the TS3 source: it works on a temporary copy of it.
"""
import argparse, json, os, shutil, sqlite3, sys, tempfile

# keys the TS6 server owns; the TS3 value must never replace them
KEEP_TS6_PROPS = {
    'virtualserver_unique_identifier', 'virtualserver_keypair',
    'virtualserver_protocol_verify_keypair', 'virtualserver_filebase',
    'virtualserver_autogenerated_privilegekey', 'virtualserver_accounting_token',
    'virtualserver_webrtc_certificate', 'virtualserver_webrtc_private_key',
}
# permissions that exist only in TS6 (found by diffing against the TS6 permissionlist)
TS6_ONLY_PERMS = [
    'b_channel_modify_ft_quotas', 'b_channel_textmessage_delete',
    'b_serverinstance_licensesign_message', 'b_virtualserver_canonical_name_manage',
    'b_virtualserver_modify_mytsid_connect', 'i_ft_max_file_size_mb',
    'i_ft_storage_mb_per_client',
    'i_needed_modify_power_channel_modify_ft_quotas',
    'i_needed_modify_power_channel_textmessage_delete',
    'i_needed_modify_power_ft_max_file_size_mb',
    'i_needed_modify_power_ft_storage_mb_per_client',
    'i_needed_modify_power_serverinstance_licensesign_message',
    'i_needed_modify_power_virtualserver_canonical_name_manage',
    'i_needed_modify_power_virtualserver_modify_mytsid_connect',
]
TEMPLATE_BY_NAME = {'Server Admin': 3, 'Normal': 4, 'Guest': 5}
PERM_TABLES = ['perm_server_group', 'perm_channel', 'perm_channel_groups']
DEFAULT_CHANNEL_QUOTA = '4294967295'


def log(*a):
    print(*a, flush=True)


def open_copy(path, tmp):
    """Open a private copy of an SQLite DB (with its WAL) so the source is never written."""
    dst = os.path.join(tmp, os.path.basename(path))
    for suffix in ('', '-wal', '-shm'):
        if os.path.exists(path + suffix):
            shutil.copy2(path + suffix, dst + suffix)
    c = sqlite3.connect(dst)
    c.row_factory = sqlite3.Row
    return c


def cols(c, table):
    return [r[1] for r in c.execute(f'pragma table_info({table})')]


def copy_rows(src, dst, table, where, args, rewrite=None, skip=None):
    """Copy rows of `table` using the columns both schemas share. Returns count."""
    common = [c for c in cols(src, table) if c in set(cols(dst, table))]
    sql = f'insert into {table} ({",".join(common)}) values ({",".join("?" * len(common))})'
    n = 0
    for row in src.execute(f'select {",".join(common)} from {table} where {where}', args):
        d = dict(row)
        if rewrite:
            rewrite(d)
        if skip and skip(d):
            continue
        dst.execute(sql, [d[c] for c in common])
        n += 1
    return n


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--ts3-db', required=True)
    ap.add_argument('--ts6-db', required=True, help='fresh TS6 database, modified in place')
    ap.add_argument('--perm-list', required=True, help='TS6 permissionlist JSON from the Web Query')
    ap.add_argument('--legacy-out', required=True, help='side database for the remapper')
    ap.add_argument('--src-server', type=int, default=6)
    ap.add_argument('--dst-server', type=int, default=1)
    ap.add_argument('--dry-run', action='store_true', help='do everything, then roll back')
    a = ap.parse_args()
    S, D = a.src_server, a.dst_server

    tmp = tempfile.mkdtemp(prefix='ts3copy-')
    t3 = open_copy(a.ts3_db, tmp)
    t6 = sqlite3.connect(a.ts6_db)
    t6.row_factory = sqlite3.Row
    t6.execute('pragma foreign_keys=off')
    known_perms = {p['permname'] for p in json.load(open(a.perm_list))['body']}
    if t3.execute('pragma integrity_check').fetchone()[0] != 'ok':
        sys.exit('TS3 copy fails integrity_check, aborting')

    # --- preflight: the target must be the untouched fresh TS6 state
    ch = t6.execute('select channel_id from channels where server_id=?', (D,)).fetchall()
    if [r[0] for r in ch] != [1]:
        sys.exit(f'target is not a fresh TS6 database (channels={[r[0] for r in ch]}); refusing')
    if t6.execute('select count(*) from servers where server_id=?', (D,)).fetchone()[0] != 1:
        sys.exit('target has no server row for dst-server')
    if t3.execute('select count(*) from servers where server_id=?', (S,)).fetchone()[0] != 1:
        sys.exit('source server id not found')

    # IDs are kept, so make sure they cannot collide with what TS6 keeps (templates, server 0)
    keep_g = {r[0] for r in t6.execute('select group_id from groups_server where server_id!=?', (D,))}
    keep_cg = {r[0] for r in t6.execute('select group_id from groups_channel where server_id!=?', (D,))}
    src_g = {r[0] for r in t3.execute('select group_id from groups_server where server_id=?', (S,))}
    src_cg = {r[0] for r in t3.execute('select group_id from groups_channel where server_id=?', (S,))}
    if keep_g & src_g or keep_cg & src_cg:
        sys.exit('group id collision with TS6 template groups, aborting')

    stats = {}
    t6.execute('begin')

    # --- wipe the fresh default content of the target server
    for tb in ['channels', 'channel_properties', 'groups_server', 'groups_channel',
               'perm_server_group', 'perm_channel', 'perm_channel_groups', 'perm_client',
               'perm_channel_clients', 'group_server_to_client', 'group_channel_to_client',
               'tokens', 'bans', 'messages']:
        t6.execute(f'delete from {tb} where server_id=?', (D,))
    # non-template groups/perms of the old defaults are gone with the delete above

    sid = lambda d: d.__setitem__('server_id', D)

    # --- channels
    stats['channels'] = copy_rows(t3, t6, 'channels', 'server_id=?', (S,), sid)

    def fix_chan_prop(d):
        d['server_id'] = D
        if d['ident'] == 'channel_filepath':
            d['value'] = d['value'].replace(f'virtualserver_{S}/', f'virtualserver_{D}/')
    stats['channel_properties'] = copy_rows(t3, t6, 'channel_properties', 'server_id=?', (S,), fix_chan_prop)
    for (cid,) in t3.execute('select channel_id from channels where server_id=?', (S,)).fetchall():
        if not t6.execute("select 1 from channel_properties where server_id=? and id=? and ident='channel_storage_quota'", (D, cid)).fetchone():
            t6.execute('insert into channel_properties (server_id,id,ident,value) values (?,?,?,?)',
                       (D, cid, 'channel_storage_quota', DEFAULT_CHANNEL_QUOTA))

    # --- groups
    stats['groups_server'] = copy_rows(t3, t6, 'groups_server', 'server_id=?', (S,), sid)
    stats['groups_channel'] = copy_rows(t3, t6, 'groups_channel', 'server_id=?', (S,), sid)

    # --- permissions (drop names TS6 does not know)
    skipped = []
    for tb in PERM_TABLES:
        def unknown(d, tb=tb):
            if d['perm_id'] not in known_perms:
                skipped.append((tb, d['id1'], d['perm_id'], d['perm_value']))
                return True
            return False
        stats[tb] = copy_rows(t3, t6, tb, 'server_id=?', (S,), sid, unknown)

    # --- new TS6 permissions for groups named like a TS6 template (heuristic, see report)
    granted = 0
    for g in t6.execute('select group_id,name from groups_server where server_id=?', (D,)).fetchall():
        tpl = TEMPLATE_BY_NAME.get(g['name'])
        if not tpl:
            continue
        for p in t6.execute(f'select * from perm_server_group where server_id=0 and id1=? and perm_id in ({",".join("?"*len(TS6_ONLY_PERMS))})',
                            (tpl, *TS6_ONLY_PERMS)).fetchall():
            if not t6.execute('select 1 from perm_server_group where server_id=? and id1=? and perm_id=?', (D, g['group_id'], p['perm_id'])).fetchone():
                t6.execute('insert into perm_server_group (server_id,id1,id2,perm_id,perm_value,perm_negated,perm_skip) values (?,?,?,?,?,?,?)',
                           (D, g['group_id'], p['id2'], p['perm_id'], p['perm_value'], p['perm_negated'], p['perm_skip']))
                granted += 1
    stats['new_ts6_perms_granted_by_group_name'] = granted

    # --- server properties: TS6 base, overlaid with TS3 values for shared keys
    cur = {r['ident']: r['value'] for r in t6.execute('select ident,value from server_properties where server_id=?', (D,))}
    n = 0
    for r in t3.execute('select ident,value from server_properties where server_id=?', (S,)):
        if r['ident'] in KEEP_TS6_PROPS or r['ident'] not in cur:
            continue
        # TS3 stores "unlimited" as the 64-bit max; where TS6 uses a narrower type
        # (e.g. quotas, 4294967295) that value fails to load, so keep the TS6 default
        if r['value'] == '18446744073709551615' and cur[r['ident']] != r['value']:
            continue
        t6.execute('update server_properties set value=? where server_id=? and ident=?', (r['value'], D, r['ident']))
        n += 1
    t6.execute("update server_properties set value='' where server_id=? and ident='virtualserver_autogenerated_privilegekey'", (D,))
    # TS3 can keep a stale password hash while flag_password=0 (no password in effect);
    # TS6 treats any non-empty password as active, so only carry it over when the flag is on
    flag = t3.execute("select value from server_properties where server_id=? and ident='virtualserver_flag_password'", (S,)).fetchone()
    if not flag or flag['value'] != '1':
        t6.execute("update server_properties set value='' where server_id=? and ident='virtualserver_password'", (D,))
        t6.execute("update server_properties set value='0' where server_id=? and ident='virtualserver_flag_password'", (D,))
    stats['server_properties_overlaid'] = n

    # --- tokens (privilege keys) and IP-only bans
    stats['tokens'] = copy_rows(t3, t6, 'tokens', 'server_id=?', (S,), sid)
    stats['bans_ip'] = copy_rows(t3, t6, 'bans', "server_id=? and coalesce(ban_uid,'')=''", (S,), sid)

    # --- side database for the remapper (everything keyed by SHA-1 client UID)
    if os.path.exists(a.legacy_out):
        os.remove(a.legacy_out)
    lg = sqlite3.connect(a.legacy_out)
    lg.executescript('''
      create table legacy_clients(old_client_id integer primary key, sha1_uid text unique, nickname text,
        login_name text, lastconnected integer, lastip text, totalconnections integer, total_upload integer, total_download integer);
      create table legacy_server_groups(old_client_id integer, group_id integer);
      create table legacy_channel_groups(old_client_id integer, channel_id integer, group_id integer);
      create table legacy_client_perms(old_client_id integer, perm_id text, perm_value integer, perm_negated integer, perm_skip integer);
      create table legacy_channel_client_perms(channel_id integer, old_client_id integer, perm_id text, perm_value integer, perm_negated integer, perm_skip integer);
      create table legacy_uid_bans(ban_uid text, ban_name text, ban_timestamp integer, ban_length integer, ban_reason text, ban_invoker_name text, ban_lastnickname text);
      create table legacy_messages(message_id integer, from_old_client_id integer, from_sha1_uid text, to_old_client_id integer, subject text, msg text, ts integer, flag_read integer);
      create table legacy_client_props(old_client_id integer, ident text, value text);
      create table meta(k text, v text);
    ''')
    lg.executemany('insert into legacy_clients values (?,?,?,?,?,?,?,?,?)',
                   [tuple(r) for r in t3.execute('select client_id,client_unique_id,client_nickname,client_login_name,client_lastconnected,client_lastip,client_totalconnections,client_total_upload,client_total_download from clients where server_id=?', (S,))])
    lg.executemany('insert into legacy_server_groups values (?,?)',
                   [tuple(r) for r in t3.execute('select id1,group_id from group_server_to_client where server_id=?', (S,))])
    lg.executemany('insert into legacy_channel_groups values (?,?,?)',
                   [tuple(r) for r in t3.execute('select id1,id2,group_id from group_channel_to_client where server_id=?', (S,))])
    lg.executemany('insert into legacy_client_perms values (?,?,?,?,?)',
                   [tuple(r) for r in t3.execute('select id1,perm_id,perm_value,perm_negated,perm_skip from perm_client where server_id=?', (S,)) if r['perm_id'] in known_perms])
    lg.executemany('insert into legacy_channel_client_perms values (?,?,?,?,?,?)',
                   [tuple(r) for r in t3.execute('select id1,id2,perm_id,perm_value,perm_negated,perm_skip from perm_channel_clients where server_id=?', (S,)) if r['perm_id'] in known_perms])
    lg.executemany('insert into legacy_uid_bans values (?,?,?,?,?,?,?)',
                   [tuple(r) for r in t3.execute("select ban_uid,ban_name,ban_timestamp,ban_length,ban_reason,ban_invoker_name,ban_lastnickname from bans where server_id=? and coalesce(ban_uid,'')!=''", (S,))])
    lg.executemany('insert into legacy_messages values (?,?,?,?,?,?,?,?)',
                   [tuple(r) for r in t3.execute('select message_id,message_from_client_id,message_from_client_uid,message_to_client_id,message_subject,message_msg,message_timestamp,message_flag_read from messages where server_id=?', (S,))])
    lg.executemany('insert into legacy_client_props values (?,?,?)',
                   [tuple(r) for r in t3.execute("select id,ident,value from client_properties where server_id=? and ident in ('client_flag_avatar','client_description','client_created') and value!=''", (S,))])
    lg.execute('insert into meta values (?,?)', ('src_server', str(S)))
    lg.commit()
    for tb in ['legacy_clients', 'legacy_server_groups', 'legacy_channel_groups', 'legacy_client_perms',
               'legacy_channel_client_perms', 'legacy_uid_bans', 'legacy_messages', 'legacy_client_props']:
        stats[f'side:{tb}'] = lg.execute(f'select count(*) from {tb}').fetchone()[0]
    lg.close()

    # --- consistency checks on the result
    problems = []
    q = lambda s, *p: t6.execute(s, p).fetchall()
    if q("select count(*) c from channel_properties where server_id=? and ident='channel_flag_default' and value='1'", D)[0]['c'] != 1:
        problems.append('expected exactly one default channel')
    orphan = q('select count(*) c from channels c where server_id=? and channel_parent_id!=0 and channel_parent_id not in (select channel_id from channels)', D)[0]['c']
    if orphan: problems.append(f'{orphan} channels with missing parent')
    for prop in ('virtualserver_default_server_group', 'virtualserver_default_channel_group', 'virtualserver_default_channel_admin_group'):
        v = int(q('select value from server_properties where server_id=? and ident=?', D, prop)[0]['value'])
        tbl = 'groups_server' if 'server_group' in prop else 'groups_channel'
        if not q(f'select 1 from {tbl} where group_id=?', v):
            problems.append(f'{prop}={v} does not exist')
    for tb, key, ref in [('perm_channel', 'id1', 'channels'), ('perm_server_group', 'id1', 'groups_server'),
                         ('perm_channel_groups', 'id1', 'groups_channel')]:
        refcol = 'channel_id' if ref == 'channels' else 'group_id'
        bad = q(f'select count(*) c from {tb} where server_id=? and {key} not in (select {refcol} from {ref})', D)[0]['c']
        if bad: problems.append(f'{bad} rows in {tb} point to missing {ref}')

    log('--- result' + (' (DRY RUN, rolled back)' if a.dry_run else ''))
    for k, v in stats.items():
        log(f'  {k:46} {v}')
    log(f'  permission rows skipped (unknown to TS6):      {len(skipped)}')
    for s in skipped:
        log('     ', s)
    log('  problems:', problems or 'none')
    if problems or a.dry_run:
        t6.rollback()
        sys.exit(1 if problems else 0)
    t6.commit()
    t6.execute('pragma wal_checkpoint(TRUNCATE)')
    log('  integrity_check:', t6.execute('pragma integrity_check').fetchone()[0])
    shutil.rmtree(tmp, ignore_errors=True)


if __name__ == '__main__':
    main()
